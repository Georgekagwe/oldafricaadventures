/* Old Africa Adventures — gallery data generator
   Scans assets/gallery/<Category>/ for photos and videos and (re)writes
   js/gallery-data.js so gallery.html always reflects what's actually in
   the folder.

   Run it after adding or removing files:
     node tools/generate-gallery-data.js

   Each subfolder of assets/gallery/ becomes a category (its name is shown
   on the gallery page's filter pills, capitalised as-is — e.g. "Safari").
   Supported files: .jpg .jpeg .png (images) and .mp4 .mov (videos).

   Images get a matching thumbnail at assets/gallery/thumbs/<Category>/.
   If you add new photos, also run tools/generate-gallery-thumbs.js
   (requires the "sharp" package — see that file's header) so the new
   photos get a lightweight thumbnail instead of loading full-size in the
   grid. Entries here point at the thumb regardless of whether it exists
   yet; gallery.js falls back to the full image if a thumb 404s.

   Every entry gets a stable, sequential "id" number (shown as a small
   badge in the corner of its tile on gallery.html) plus a `// #<id>`
   comment above it here — so if you spot a photo you don't like on the
   live page, you can find its exact block in this file by that number and
   delete it, then re-run this script (it'll renumber the rest). */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const GALLERY_DIR = path.join(ROOT, 'assets', 'gallery');
const OUT_FILE = path.join(ROOT, 'js', 'gallery-data.js');

const IMAGE_EXTS = new Set(['.jpg', '.jpeg', '.png']);
const VIDEO_EXTS = new Set(['.mp4', '.mov']);

// Add a file's relative path here (e.g. "assets/gallery/Safari/foo.mp4")
// to keep it on disk but leave it out of the published gallery grid.
// Two reasons you'd do this:
//  1. The file is over GitHub's 100MB push limit, until it's compressed,
//     moved to Git LFS, or hosted externally.
//  2. It's used directly as gallery.html's hero background image (see the
//     <section class="hero..."> at the top of that file) — keeping it out
//     of the numbered grid means a future bulk delete-by-ID can't remove
//     it out from under the hero without you noticing.
const SKIP_FILES = new Set([
  'assets/gallery/Safari/20260410_184031.jpg', // gallery.html hero image
]);

function scanCategory(categoryDir, categoryName) {
  const items = [];
  for (const file of fs.readdirSync(categoryDir).sort()) {
    const ext = path.extname(file).toLowerCase();
    const full = path.join(categoryDir, file);
    if (!fs.statSync(full).isFile()) continue;

    const srcRel = `assets/gallery/${categoryName}/${file}`.replace(/\\/g, '/');
    if (SKIP_FILES.has(srcRel)) continue;

    if (IMAGE_EXTS.has(ext)) {
      const thumbName = path.basename(file, ext) + '.jpg';
      items.push({
        type: 'image',
        src: srcRel,
        thumb: `assets/gallery/thumbs/${categoryName}/${thumbName}`.replace(/\\/g, '/'),
        file,
      });
    } else if (VIDEO_EXTS.has(ext)) {
      items.push({ type: 'video', src: srcRel, file });
    }
  }
  return items;
}

// Hand-formats one item as JS, with a `// #<id> — <filename>` comment above
// it, rather than JSON.stringify-ing the whole thing — comments aren't
// valid JSON, but they're what makes finding-and-deleting one entry easy.
function formatItem(item, indent) {
  const pad = ' '.repeat(indent);
  const inner = pad + '    ';
  const fields = [`id: ${item.id}`, `type: "${item.type}"`, `src: "${item.src}"`];
  if (item.type === 'image') fields.push(`thumb: "${item.thumb}"`);
  const fieldLines = fields.map(f => inner + f).join(',\n');
  return `${pad}// #${item.id} — ${item.file}\n${pad}{\n${fieldLines}\n${pad}},`;
}

function build() {
  if (!fs.existsSync(GALLERY_DIR)) {
    console.error('No assets/gallery/ folder found.');
    process.exit(1);
  }

  const categories = fs.readdirSync(GALLERY_DIR)
    .filter(name => name !== 'thumbs')
    .filter(name => fs.statSync(path.join(GALLERY_DIR, name)).isDirectory())
    .sort();

  let nextId = 1;
  const categoryBlocks = [];
  let imageCount = 0, videoCount = 0;

  for (const category of categories) {
    const items = scanCategory(path.join(GALLERY_DIR, category), category);
    items.forEach(item => { item.id = nextId++; });
    imageCount += items.filter(i => i.type === 'image').length;
    videoCount += items.filter(i => i.type === 'video').length;

    const itemLines = items.map(item => formatItem(item, 8)).join('\n');
    categoryBlocks.push(`    "${category}": [\n${itemLines}\n    ],`);
  }

  const header = `/* Old Africa Adventures — gallery content
   Auto-generated by tools/generate-gallery-data.js — re-run that script
   after adding/removing files in assets/gallery/ rather than hand-editing
   the entries below (it renumbers everything for you). Safe to hand-edit
   the file header/comments, or to delete a whole numbered entry yourself
   if you don't want to wait to re-run the script.

   To remove a photo/video: find its "// #<id>" comment below (the same
   number appears as a small badge on its tile on gallery.html), delete
   that whole { ... } block including the comment above it, and delete the
   original file from assets/gallery/ too if you don't want it kept at
   all. IDs will have a gap until you next re-run the generator — that's
   fine, they don't need to be contiguous.

   Structure: { "<Category>": [ { id, type: "image", src, thumb } | { id, type: "video", src } ] }
   gallery.html / js/gallery.js read this to build the grid + lightbox. */

`;

  const body = `const OAA_GALLERY = {\n${categoryBlocks.join('\n')}\n};\n`;

  fs.writeFileSync(OUT_FILE, header + body);
  console.log(`Wrote ${OUT_FILE}`);
  console.log(`Categories: ${categories.join(', ')}`);
  console.log(`Images: ${imageCount}, Videos: ${videoCount}`);
}

build();
